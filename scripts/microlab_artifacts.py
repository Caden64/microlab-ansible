#!/usr/bin/env python3
"""Stage pinned controller artifacts, never contact inventory hosts.

CLI: --inventory FILE --directory DIR [--offline] [--check]. Requires PyYAML.
stdout: one JSON object (schema_version, status, architecture, group_vars,
artifacts, acceptance). Errors use status=error, error; exit 1. --check implies
no network and no writes; --offline validates local inputs and may publish vars.
Generated vars: group_vars/microlab_management/zz_microlab_artifacts.yml.
Only this dedicated, marked file is replaced; main.yml/vault.yml are untouched.
Custom versions require explicit SHA256 and staged inputs (no guessed URLs).
Publisher HTTPS hashes pin bytes; signature verification and service acceptance
are separate. This module does not create CA material or run binaries.
"""
import argparse
import ctypes
import errno
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import struct
import sys
import tarfile
import tempfile
import urllib.error
import urllib.request

try:
    import yaml
except ImportError:
    raise SystemExit('PyYAML is required: install the controller Ansible dependencies first')

LOCK = Path(__file__).resolve().parents[1] / 'config/artifacts.lock.json'
GENERATED = 'zz_microlab_artifacts.yml'
MARKER = '# Generated by microlab_artifacts.py; controller artifacts only.\n'
ARCHES = {'amd64': 62, 'arm64': 183}
VARS = {
    'technitium': 'micolab_technitium',
    'dotnet-aspnetcore-runtime': 'micolab_dotnet_aspnetcore_runtime',
    'caddy': 'micolab_caddy', 'forgejo': 'micolab_forgejo',
    'step-ca': 'microlab_step_ca', 'step-cli': 'microlab_step_cli',
}


class ArtifactError(Exception):
    pass


class InventoryLoader(yaml.SafeLoader):
    pass


# Treat inline vault as opaque: never invoke Ansible, decrypt, or print values.
InventoryLoader.add_constructor('!vault', lambda loader, node: None)


def read_yaml(path):
    try:
        text = path.read_text()
        if text.startswith('$ANSIBLE_VAULT;'):
            return {}
        result = yaml.load(text, Loader=InventoryLoader) or {}
        if not isinstance(result, dict):
            raise ArtifactError(f'{path}: expected a YAML mapping')
        return result
    except (yaml.YAMLError, UnicodeError):
        raise ArtifactError(f'{path}: invalid YAML (contents suppressed)') from None


def meaningful(value):
    return value not in (None, '', {}, []) and not (
        isinstance(value, str) and 'REPLACE_' in value)


def inventory_values(inventory):
    """Read static YAML only. Fail on ambiguous supported pins; no dynamic inventory."""
    root = read_yaml(inventory)
    hosts, definitions = {}, []

    def walk(name, group, inherited, ancestors):
        if not isinstance(group, dict):
            raise ArtifactError('Inventory groups must be YAML mappings')
        merged = {**inherited, **(group.get('vars') or {})}
        relevant = name == 'microlab_management' or inherited.get('__management')
        branch = ancestors + [group.get('vars') or {}]
        if relevant:
            definitions.extend(branch)
        for host, values in (group.get('hosts') or {}).items():
            values = values or {}
            if relevant:
                definitions.append(values)
                hosts[host] = {**merged, **values}
        for child, values in (group.get('children') or {}).items():
            walk(child, values or {}, {**merged, '__management': name == 'microlab_management' or inherited.get('__management', False)}, branch)
    walk('all', root.get('all', root), {}, [])
    if len(hosts) != 1:
        raise ArtifactError('Static inventory must contain exactly one microlab_management infra host; all four infra services stay together')
    host = next(iter(hosts))
    # Explicit values in all/management/host vars are considered, never secrets.
    for kind, names in [('group_vars', ['all', 'microlab_management']), ('host_vars', [host])]:
        for name in names:
            base = inventory.parent / kind / name
            candidates = [base.with_suffix('.yml'), base.with_suffix('.yaml')]
            if base.is_dir():
                candidates += sorted(p for p in base.iterdir() if p.suffix in ('.yml', '.yaml', '.json') and p.name != GENERATED)
            elif base.is_file():
                candidates.append(base)
            for path in candidates:
                if path.is_file():
                    definitions.append(read_yaml(path))
    arch_values = {d['micolab_expected_architecture'] for d in definitions if meaningful(d.get('micolab_expected_architecture'))}
    if len(arch_values) != 1 or next(iter(arch_values)) not in ARCHES:
        raise ArtifactError('Set one consistent micolab_expected_architecture: amd64 or arm64 in the infra inventory; controller CPU is never used')
    return next(iter(arch_values)), definitions


def one_pin(values, label):
    values = [v for v in values if meaningful(v)]
    if any(not isinstance(v, str) or '{{' in v for v in values):
        raise ArtifactError(f'{label}: use a literal pin, not a template')
    if len(set(values)) > 1:
        raise ArtifactError(f'{label}: conflicting explicit inventory pins; reconcile them without resetting inventory')
    return values[0] if values else None


def confined(root, name):
    path = root / name
    if Path(name).name != name or path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
        raise ArtifactError('Artifact destination escapes the chosen directory or is a symlink')
    return path


def digest(path, algorithm='sha256'):
    h = hashlib.new(algorithm)
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def elf_header(data, arch):
    if len(data) < 20 or data[:6] != b'\x7fELF\x02\x01' or struct.unpack('<H', data[18:20])[0] != ARCHES[arch]:
        raise ArtifactError(f'Expected a Linux 64-bit {arch} ELF binary; wrong architecture or format')


def validate(path, entry, arch, name):
    if not path.is_file() or digest(path) != entry['sha256']:
        raise ArtifactError(f'{name}: missing file or SHA256 mismatch at {path}; preserve it and supply matching pinned bytes')
    for algorithm, expected in entry.get('publisher_hash', {}).items():
        if digest(path, algorithm) != expected:
            raise ArtifactError(f'{name}: publisher {algorithm} mismatch')
    if name == 'forgejo':
        with path.open('rb') as stream:
            elf_header(stream.read(20), arch)
        return
    try:
        with tarfile.open(path, 'r:gz') as archive:
            members = {}
            for member in archive:
                p = PurePosixPath(member.name)
                if p.is_absolute() or '..' in p.parts or member.isdev() or member.issym() or member.islnk():
                    raise ArtifactError(f'{name}: unsafe archive member or link')
                members[str(p)] = member
            expected = entry['member']
            member = members.get(expected)
            if member is None or not member.isfile():
                raise ArtifactError(f'{name}: archive must contain {expected} for the native role layout')
            if name != 'technitium':
                with archive.extractfile(member) as stream:
                    elf_header(stream.read(20), arch)
    except (tarfile.TarError, EOFError, OSError):
        raise ArtifactError(f'{name}: invalid or truncated archive at {path}') from None


def download(url, destination):
    if not url.startswith('https://') or '/latest/' in url:
        raise ArtifactError('Downloads require an explicit versioned HTTPS publisher URL')
    try:
        request = urllib.request.Request(url, headers={'User-Agent': 'microlab-artifacts/1'})
        with urllib.request.urlopen(request, timeout=45) as response, destination.open('wb') as stream:
            if not response.geturl().startswith('https://'):
                raise ArtifactError('Publisher redirected to insecure transport')
            shutil.copyfileobj(response, stream)
    except (urllib.error.URLError, TimeoutError, OSError):
        raise ArtifactError(f'Download failed for {url}; check public HTTPS/DNS access, retry, or stage the pinned file and use --offline') from None


def plan(arch, definitions, lock, directory):
    planned, extras = [], {}
    for d in definitions:
        for item in d.get('micolab_staged_artifacts', []) or []:
            if not isinstance(item, dict) or not isinstance(item.get('name'), str):
                raise ArtifactError('micolab_staged_artifacts must contain named mappings')
            if item['name'] not in VARS:
                if item['name'] in extras and extras[item['name']] != item:
                    raise ArtifactError('Conflicting extra staged artifact entries')
                extras[item['name']] = item
    for name, prefix in VARS.items():
        staged = [i for d in definitions for i in (d.get('micolab_staged_artifacts', []) or []) if i.get('name') == name]
        version = one_pin([d.get(prefix + '_version') for d in definitions] + [i.get('version') for i in staged], name + ' version')
        checksum = one_pin([d.get(prefix + '_checksums', {}).get(arch) for d in definitions] + [i.get('sha256') for i in staged], name + ' SHA256')
        source = one_pin([d.get(prefix + '_artifact_src' + ('_' + arch if name in ('caddy', 'forgejo') else '')) for d in definitions] + [i.get('path') for i in staged], name + ' controller source')
        entry = dict(lock['artifacts'][name][arch])
        version = version or entry['version']
        if not re.fullmatch(r'\d+\.\d+\.\d+', version):
            raise ArtifactError(f'{name}: expected a numeric x.y.z version')
        if version != entry['version']:
            if not checksum or not source:
                raise ArtifactError(f'{name}: custom version requires an explicit SHA256 and staged controller path; no download URL is guessed')
            entry = dict(version=version, filename=f'{name}-{version}-{arch}' + ('' if name == 'forgejo' else '.tar.gz'), sha256=checksum, member={'technitium': 'DnsServerApp.dll', 'dotnet-aspnetcore-runtime': 'dotnet', 'caddy': 'caddy', 'step-ca': 'step-ca', 'step-cli': f'step_{version}/bin/step'}.get(name), metadata_url='inventory explicit pin')
        elif checksum and checksum.lower() != entry['sha256']:
            raise ArtifactError(f'{name}: explicit SHA256 conflicts with publisher lock for this version; reconcile the pin, inventory was not changed')
        if not re.fullmatch('[0-9a-fA-F]{64}', entry['sha256']):
            raise ArtifactError(f'{name}: SHA256 must contain 64 hex characters')
        entry['sha256'] = entry['sha256'].lower()
        # Unique names avoid ambiguous multi-version caches. Publisher bytes stay unchanged.
        filename = f'{name}-{version}-{arch}' + ('' if name == 'forgejo' else '.tar.gz')
        target = confined(directory, filename)
        local = Path(source).expanduser() if source else target
        if source and not local.is_absolute():
            raise ArtifactError(f'{name}: staged controller paths must be absolute')
        if not source and not target.exists():
            aliases = [confined(directory, entry['filename'])]
            if name == 'dotnet-aspnetcore-runtime':
                aliases.append(directory / 'aspnetcore-runtime.tar.gz')
            for alias in aliases:
                confined(directory, alias.name)
                if alias.is_file():
                    local = alias
                    break
        planned.append((name, entry, local, target))
    return planned, list(extras.values())


def publish(temp, target):
    """Atomic no-clobber rename on Linux; atomic link fallback on other hosts."""
    libc = ctypes.CDLL(None, use_errno=True)
    rename = getattr(libc, 'renameat2', None)
    if rename is not None:
        rename.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
        rename.restype = ctypes.c_int
        if rename(-100, os.fsencode(temp), -100, os.fsencode(target), 1) == 0:
            return
        error = ctypes.get_errno()
        if error not in (errno.ENOSYS, errno.EINVAL, errno.ENOTSUP):
            raise OSError(error, os.strerror(error), str(target))
    os.link(temp, target)
    temp.unlink()


def stage(inventory, directory, offline=False, check=False, lock_path=LOCK):
    inventory = Path(inventory).resolve()
    directory = Path(directory).absolute()
    if directory.is_symlink() or directory.resolve() != directory:
        raise ArtifactError('Choose an artifact directory without symlink components')
    lock = json.loads(Path(lock_path).read_text())
    arch, definitions = inventory_values(inventory)
    planned, extras = plan(arch, definitions, lock, directory)
    generated = inventory.parent / 'group_vars' / 'microlab_management' / GENERATED
    if generated.resolve() != generated or not generated.resolve().is_relative_to(inventory.parent):
        raise ArtifactError('Generated group-var path must stay inside the inventory without symlinks')
    if generated.exists() and not generated.read_text().startswith(MARKER):
        raise ArtifactError(f'{generated}: unrecognized file; refusing to overwrite user content')
    # Validate every existing input before performing any mutation.
    for name, entry, local, target in planned:
        if local.exists():
            validate(local, entry, arch, name)
        elif offline or check or local != target:
            raise ArtifactError(f'{name}: missing staged file {local}; run online setup or supply the pinned file')
        if target.exists() and target != local:
            validate(target, entry, arch, name)
    if not check:
        directory.mkdir(parents=True, exist_ok=True)
    artifacts, variables = [], {}
    for name, entry, local, target in planned:
        action = 'reused'
        if not target.exists() and not check:
            fd, tmp = tempfile.mkstemp(prefix='.microlab-', dir=directory)
            os.close(fd)
            temp = Path(tmp)
            try:
                if local.exists():
                    shutil.copyfile(local, temp)
                    action = 'copied'
                else:
                    download(entry['url'], temp)
                    action = 'downloaded'
                validate(temp, entry, arch, name)
                # Atomic publication refuses to overwrite a concurrent file.
                try:
                    publish(temp, target)
                except FileExistsError:
                    validate(target, entry, arch, name)
            finally:
                temp.unlink(missing_ok=True)
        output_path = local if check else target
        item = dict(name=name, version=entry['version'], path=str(output_path), sha256=entry['sha256'])
        artifacts.append({**item, 'action': action, 'metadata_url': entry['metadata_url']})
        prefix = VARS[name]
        variables[prefix + '_version'] = entry['version']
        checksums = {}
        for definition in definitions:
            checksums.update(definition.get(prefix + '_checksums', {}))
        variables[prefix + '_checksums'] = {**checksums, arch: entry['sha256']}
        if name in ('step-ca', 'step-cli'):
            variables[prefix + '_artifact_src'] = str(output_path)
        elif name in ('caddy', 'forgejo'):
            variables[prefix + '_artifact_src_' + arch] = str(output_path)
    variables['micolab_staged_artifacts'] = [{k: a[k] for k in ('name', 'version', 'path', 'sha256')} for a in artifacts] + extras
    content = MARKER + yaml.safe_dump(variables, sort_keys=False)
    if not check:
        generated.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix='.microlab-vars-', dir=generated.parent)
        try:
            with os.fdopen(fd, 'w') as stream:
                stream.write(content)
            os.replace(tmp, generated)
        finally:
            Path(tmp).unlink(missing_ok=True)
    return dict(schema_version=1, status='checked' if check else 'ready', architecture=arch,
                group_vars=str(generated), artifacts=artifacts,
                acceptance='not_run', installation_readiness='artifacts_only')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--inventory', required=True, type=Path)
    parser.add_argument('--directory', required=True, type=Path)
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--check', action='store_true', help='Read-only local validation; implies offline')
    args = parser.parse_args(argv)
    try:
        result = stage(args.inventory, args.directory, args.offline, args.check)
    except (ArtifactError, OSError, ValueError, KeyError, TypeError) as exc:
        # Do not print YAML values, decrypted data, or network response bodies.
        message = str(exc) if isinstance(exc, ArtifactError) else 'Invalid artifact configuration or local I/O failure; check inventory, manifest and permissions'
        print(json.dumps(dict(schema_version=1, status='error', error=message)))
        return 1
    print(json.dumps(result))
    return 0


if __name__ == '__main__':
    sys.exit(main())
