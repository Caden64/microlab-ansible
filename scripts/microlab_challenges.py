#!/usr/bin/env python3
"""Challenge definition validation, manifest pinning and edge artifact staging.

CLI: check | manifest | artifacts with --inventory FILE --definitions DIR
[--images-dir DIR ...] [--allow-update] [--offline] [--check].
stdout: one JSON object (schema_version, status, ...). Errors print
status=error and the message; exit 1. No command here contacts an inventory
host; only `./microlab challenges deploy` runs playbooks.

- check: validate every definitions/<name>/{challenge.yaml,manifest.yml}
  against locally built guest images. Fails closed on unfilled REPLACE_
  markers, digest or size mismatches, schema drift, an image name the
  Firecracker agent would reject, or a rootfs larger than the reserved disk.
- manifest: fill REPLACE_WITH_SHA256 / REPLACE_WITH_SIZE_BYTES markers from
  the built images. Existing real pins are never silently replaced; a rebuilt
  image is a reviewed change and requires --allow-update.
- artifacts: stage the pinned Traefik edge archive for the challenge host
  into artifacts/ and publish generated variables to
  group_vars/microlab_challenge/zz_microlab_challenges_artifacts.yml. Only
  the linux_amd64 build is pinned; any other challenge host architecture
  fails closed.

Generated vars file: group_vars/microlab_challenge/zz_microlab_challenges_artifacts.yml.
Only this dedicated, marked file is replaced; nothing else in the inventory
is touched. This module never reads, stores or prints challenge flags: flags
live only in the operator's vault and are consumed by the register stage.
"""
import argparse
import ctypes
import errno
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tarfile
import tempfile
import urllib.error
import urllib.request

try:
    import yaml
except ImportError:
    raise SystemExit('PyYAML is required: install the controller Ansible dependencies first')

LOCK = Path(__file__).resolve().parents[1] / 'config/challenges.lock.json'
GENERATED = 'zz_microlab_challenges_artifacts.yml'
MARKER = '# Generated by microlab_challenges.py; challenge-host artifacts only.\n'
MANIFEST_MARKER = '# Filled by microlab challenges manifest; digests are build pins, not guesses.\n'
MANIFEST_PATH = 'manifest.yml'
CHALLENGE_PATH = 'challenge.yaml'
IMAGE_NAME_REGEX = re.compile(r'^[a-z0-9][a-z0-9._-]{0,62}$')
ID_REGEX = re.compile(r'^[a-z0-9][a-z0-9-]{0,62}$')
DNS_LABEL_REGEX = re.compile(r'^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$')
EXPOSE_KINDS = ('tcp', 'raw', 'http', 'https', 'tcp-ssl')
READINESS_KINDS = ('tcp', 'http', 'none')
ALLOWED_IMAGE_FILES = ('vmlinux', 'rootfs.ext4', 'initrd')
REQUIRED_IMAGE_FILES = ('vmlinux', 'rootfs.ext4')
ELF_MACHINES = {'amd64': 62, 'arm64': 183}


class ChallengeError(Exception):
    pass


class InventoryLoader(yaml.SafeLoader):
    pass


# Treat inline vault as opaque: never decrypt or print values.
InventoryLoader.add_constructor('!vault', lambda loader, node: None)


def read_yaml(path):
    try:
        text = Path(path).read_text()
        if text.startswith('$ANSIBLE_VAULT;'):
            return {}
        result = yaml.load(text, Loader=InventoryLoader) or {}
        if not isinstance(result, dict):
            raise ChallengeError(f'{path}: expected a YAML mapping')
        return result
    except (yaml.YAMLError, UnicodeError):
        raise ChallengeError(f'{path}: invalid YAML (contents suppressed)') from None


def challenge_topology(inventory):
    """Static two-host topology check; returns (challenge_host_name, vars)."""
    def hosts_of(group):
        node = (inventory.get('all', {}).get('children', {}) or {}).get(group, {}) or {}
        hosts = node.get('hosts', {}) or {}
        if not isinstance(hosts, dict):
            raise ChallengeError(f'{group} hosts must be a YAML mapping')
        return hosts

    infra, challenge = hosts_of('microlab_management'), hosts_of('microlab_challenge')
    if len(infra) != 1 or len(challenge) != 1:
        raise ChallengeError('Define exactly one infra host and one rCTF host in the inventory')
    name, host = next(iter(challenge.items()))
    host = host or {}
    infra_host = (next(iter(infra.values())) or {})
    if not isinstance(host, dict):
        raise ChallengeError('Challenge host variables must be a mapping')
    if host.get('ansible_host') and infra_host.get('ansible_host') and \
            str(host['ansible_host']) == str(infra_host['ansible_host']):
        raise ChallengeError('The rCTF host must have a different address from infra')
    return name, host


def challenge_inventory_values(inventory_path, inventory):
    """Static vars for the challenge host: all + group + host files, no vault."""
    name, host = challenge_topology(inventory)
    values = dict(host)

    def load(path):
        if Path(path).is_file():
            values.update(read_yaml(path))
    base = inventory_path.parent
    for group in ('all', 'microlab_challenge'):
        directory = base / 'group_vars' / group
        if directory.is_dir():
            for path in sorted(directory.iterdir()):
                if path.suffix in ('.yml', '.yaml', '.json') and path.is_file():
                    load(path)
        else:
            load(directory.with_suffix('.yml'))
            load(directory.with_suffix('.yaml'))
    host_directory = base / 'host_vars' / name
    if host_directory.is_dir():
        for path in sorted(host_directory.iterdir()):
            if path.suffix in ('.yml', '.yaml', '.json') and path.is_file():
                load(path)
    else:
        load(host_directory.with_suffix('.yml'))
        load(host_directory.with_suffix('.yaml'))
    return name, values


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def unfilled(value):
    return isinstance(value, str) and 'REPLACE_' in value


def require_mapping(value, label):
    if not isinstance(value, dict):
        raise ChallengeError(f'{label}: expected a mapping')
    return value


def validate_int(value, label, low, high):
    if not isinstance(value, int) or isinstance(value, bool) or not low <= value <= high:
        raise ChallengeError(f'{label}: expected an integer between {low} and {high}')
    return value


def load_definitions(definitions):
    definitions = Path(definitions)
    if not definitions.is_dir():
        raise ChallengeError(f'{definitions}: challenge definitions directory is missing')
    found = {}
    for child in sorted(definitions.iterdir()):
        if not child.is_dir():
            continue
        challenge = child / CHALLENGE_PATH
        manifest = child / MANIFEST_PATH
        if not challenge.is_file() or not manifest.is_file():
            raise ChallengeError(f'{child.name}: needs both {CHALLENGE_PATH} and {MANIFEST_PATH}')
        found[child.name] = (read_yaml(challenge), read_yaml(manifest))
    if not found:
        raise ChallengeError(f'{definitions}: no challenge definitions found')
    return found


def validate_challenge(name, challenge, manifest):
    """Pure validation of one definition pair; returns a normalized summary."""
    require_mapping(challenge, f'{name}/{CHALLENGE_PATH}')
    require_mapping(manifest, f'{name}/{MANIFEST_PATH}')
    if 'flags' in challenge.get('data', {}):
        raise ChallengeError(f'{name}: flags must not be stored in this repository; '
                             'deploy injects them from the vault mapping')
    definition_id = challenge.get('id')
    if not isinstance(definition_id, str) or not ID_REGEX.fullmatch(definition_id):
        raise ChallengeError(f'{name}: id must match {ID_REGEX.pattern}')
    data = require_mapping(challenge.get('data'), f'{name}: data')
    for key in ('name', 'category', 'description', 'author'):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise ChallengeError(f'{name}: data.{key} must be a non-empty string')
    if not isinstance(data.get('hidden'), bool):
        raise ChallengeError(f'{name}: data.hidden must be a boolean')
    if 'flags' in data:
        raise ChallengeError(f'{name}: data.flags must not be present (vault-injected at deploy)')
    points = data.get('points')
    if points is not None:
        points = require_mapping(points, f'{name}: points')
        low = validate_int(points.get('min'), f'{name}: points.min', 0, 10 ** 6)
        high = validate_int(points.get('max'), f'{name}: points.max', 0, 10 ** 6)
        if low > high:
            raise ChallengeError(f'{name}: points.min must not exceed points.max')
    config = require_mapping(data.get('instancerConfig'), f'{name}: instancerConfig')
    if config.get('instancer') != 'firecracker':
        raise ChallengeError(f'{name}: this tooling deploys the firecracker instancer only')
    integration = config.get('challengeIntegrationId')
    if integration != definition_id:
        raise ChallengeError(f'{name}: challengeIntegrationId must equal id ({definition_id}); '
                             'it never changes after launch')
    validate_int(config.get('timeoutMilliseconds', 600000), f'{name}: timeoutMilliseconds', 1000, 7 * 24 * 3600 * 1000)
    guest = require_mapping(config.get('config'), f'{name}: instancerConfig.config')
    image = guest.get('image')
    if not isinstance(image, str) or not IMAGE_NAME_REGEX.fullmatch(image):
        raise ChallengeError(f'{name}: instancerConfig.config.image must match {IMAGE_NAME_REGEX.pattern}')
    validate_int(guest.get('vcpus', 1), f'{name}: vcpus', 1, 8)
    mem = validate_int(guest.get('memMiB', 256), f'{name}: memMiB', 64, 1 << 20)
    disk = validate_int(guest.get('diskMiB', 1024), f'{name}: diskMiB', 64, 1 << 20)
    if not isinstance(guest.get('egress', False), bool):
        raise ChallengeError(f'{name}: egress must be a boolean')
    readiness = guest.get('readiness')
    if readiness is not None:
        readiness = require_mapping(readiness, f'{name}: readiness')
        if readiness.get('kind') not in READINESS_KINDS:
            raise ChallengeError(f'{name}: readiness.kind must be one of {READINESS_KINDS}')
        if readiness.get('kind') != 'none':
            validate_int(readiness.get('port'), f'{name}: readiness.port', 1, 65535)
    expose = config.get('expose')
    if not isinstance(expose, list) or not 1 <= len(expose) <= 16:
        raise ChallengeError(f'{name}: expose must list 1 to 16 entries')
    kinds = []
    for index, entry in enumerate(expose):
        label = f'{name}: expose[{index}]'
        require_mapping(entry, label)
        if entry.get('kind') not in EXPOSE_KINDS:
            raise ChallengeError(f'{label}: kind must be one of {EXPOSE_KINDS}')
        kinds.append(entry['kind'])
        if entry.get('containerName') != 'app':
            raise ChallengeError(f'{label}: the Firecracker instancer requires containerName "app"')
        validate_int(entry.get('containerPort'), f'{label}: containerPort', 1, 65535)
        prefix = entry.get('hostPrefix')
        if not isinstance(prefix, str) or not DNS_LABEL_REGEX.fullmatch(prefix) or len(prefix) > 32:
            raise ChallengeError(f'{label}: hostPrefix must be a DNS label of at most 32 characters')
        if entry['kind'] in ('http', 'https', 'tcp-ssl') and not prefix:
            raise ChallengeError(f'{label}: kind {entry["kind"]} needs a hostPrefix')
        if entry.get('shouldDisplay') is not True:
            raise ChallengeError(f'{label}: shouldDisplay must be true or players see no endpoint')
    # Manifest side
    if manifest.get('image') != image:
        raise ChallengeError(f'{name}: manifest image {manifest.get("image")!r} != challenge image {image!r}')
    files = manifest.get('files')
    if not isinstance(files, list) or not files:
        raise ChallengeError(f'{name}/{MANIFEST_PATH}: files must be a non-empty list')
    entries = {}
    for entry in files:
        require_mapping(entry, f'{name}/{MANIFEST_PATH} files')
        filename = entry.get('name')
        if filename not in ALLOWED_IMAGE_FILES:
            raise ChallengeError(f'{name}: image file {filename!r} is not one of {ALLOWED_IMAGE_FILES}')
        if filename in entries:
            raise ChallengeError(f'{name}: duplicate manifest entry for {filename}')
        if unfilled(entry.get('sha256')) or unfilled(entry.get('size')):
            raise ChallengeError(f'{name}: manifest pin for {filename} is unfilled; '
                                 'run ./microlab challenges manifest')
        if not re.fullmatch('[0-9a-fA-F]{64}', str(entry['sha256'])):
            raise ChallengeError(f'{name}: manifest sha256 for {filename} must be 64 hex characters')
        validate_int(entry.get('size'), f'{name}: manifest size for {filename}', 1, 1 << 40)
        entries[filename] = entry
    for required in REQUIRED_IMAGE_FILES:
        if required not in entries:
            raise ChallengeError(f'{name}/{MANIFEST_PATH}: missing required file {required}')
    return dict(id=definition_id, name=data['name'], category=data['category'], image=image,
                kinds=kinds, disk_mib=disk, mem_mib=mem, data=data,
                files=[dict(name=key, sha256=str(entries[key]['sha256']).lower(),
                            size=int(entries[key]['size'])) for key in
                       (key for key in ALLOWED_IMAGE_FILES if key in entries)])


def resolve_images(definitions, images_dirs):
    """Locate and digest-check every manifest file under the images directories."""
    images_dirs = [Path(directory).expanduser().resolve() for directory in images_dirs]
    for directory in images_dirs:
        if not directory.is_dir():
            raise ChallengeError(f'images directory not found: {directory}')
    resolved = []
    for label, (challenge, manifest) in definitions.items():
        summary = validate_challenge(label, challenge, manifest)
        staged = []
        for entry in summary['files']:
            found = None
            for directory in images_dirs:
                candidate = directory / summary['image'] / entry['name']
                if candidate.is_file() and not candidate.is_symlink():
                    found = candidate
                    break
            if found is None:
                searched = ', '.join(str(directory / summary['image']) for directory in images_dirs)
                raise ChallengeError(f'{label}: image file {summary["image"]}/{entry["name"]} '
                                     f'was not found in: {searched}')
            actual = digest(found)
            if actual != entry['sha256']:
                raise ChallengeError(f'{label}: {summary["image"]}/{entry["name"]} sha256 mismatch: '
                                     f'built {actual} != pinned {entry["sha256"]}; rebuild the lab or '
                                     're-pin with ./microlab challenges manifest --allow-update')
            size = found.stat().st_size
            if size != entry['size']:
                raise ChallengeError(f'{label}: {summary["image"]}/{entry["name"]} size changed: '
                                     f'{size} != pinned {entry["size"]}')
            if entry['name'] == 'rootfs.ext4' and size > summary['disk_mib'] * 1048576:
                raise ChallengeError(f'{label}: rootfs.ext4 is {size} bytes but the challenge reserves '
                                     f'only {summary["disk_mib"]} MiB of writable disk; raise diskMiB')
            staged.append(dict(entry, path=str(found)))
        summary['files'] = staged
        summary['needs_edge'] = any(kind in ('http', 'https', 'tcp-ssl') for kind in summary['kinds'])
        summary['image_files'] = [dict(image=summary['image'], definition=summary['id'],
                                       name=f['name'], path=f['path'], sha256=f['sha256'],
                                       size=f['size']) for f in staged]
        resolved.append(summary)
    return resolved


def definitions_result(item):
    return dict(
        id=item['id'], name=item['name'], category=item['category'], image=item['image'],
        kinds=item['kinds'], needs_edge=item['needs_edge'], disk_mib=item['disk_mib'],
        mem_mib=item['mem_mib'], data=item['data'],
        files=[dict(name=f['name'], path=f['path'], sha256=f['sha256'], size=f['size'])
               for f in item['files']],
        image_files=[dict(image=item['image'], definition=item['id'], name=f['name'],
                          path=f['path'], sha256=f['sha256'], size=f['size'])
                     for f in item['files']])


def run_check(definitions, images_dirs):
    resolved = resolve_images(load_definitions(definitions), images_dirs)
    result = dict(status='ready', definitions=[definitions_result(item) for item in resolved])
    # Staged records share one image: the staging loop wants each physical
    # file once, while per-record checks above still validate every pin.
    seen = set()
    image_files = []
    for item in resolved:
        for entry in item['image_files']:
            key = (entry['image'], entry['name'])
            if key not in seen:
                seen.add(key)
                image_files.append(entry)
    result['image_files'] = image_files
    return result


def run_manifest(definitions, images_dirs, allow_update):
    """Fill REPLACE_ markers from the built images.

    Manifest mode is marker-aware: an unfilled pin is filled in place; a real
    pin whose bytes differ is a rebuild and needs --allow-update. Schema-level
    validation stays the job of check mode, which deploy always runs first.
    """
    written = []
    for child in sorted(Path(definitions).iterdir()):
        if not child.is_dir() or not (child / MANIFEST_PATH).is_file():
            continue
        manifest = read_yaml(child / MANIFEST_PATH)
        image = manifest.get('image')
        if not isinstance(image, str) or not IMAGE_NAME_REGEX.fullmatch(image):
            raise ChallengeError(f'{child.name}: manifest image is invalid')
        new_files = []
        changed = False
        for entry in (manifest.get('files') or []):
            require_mapping(entry, f'{child.name}/{MANIFEST_PATH} files')
            filename = entry.get('name')
            if filename not in ALLOWED_IMAGE_FILES:
                raise ChallengeError(f'{child.name}: unknown image file {filename!r}')
            found = None
            for directory in images_dirs:
                candidate = Path(directory).expanduser().resolve() / image / filename
                if candidate.is_file() and not candidate.is_symlink():
                    found = candidate
                    break
            if found is None:
                raise ChallengeError(f'{child.name}: {image}/{filename} was not found in the images directories')
            actual_sha, actual_size = digest(found), found.stat().st_size
            pinned_sha, pinned_size = entry.get('sha256'), entry.get('size')
            if pinned_sha is None or pinned_size is None or \
                    unfilled(pinned_sha) or unfilled(pinned_size):
                changed = True
            elif str(pinned_sha).lower() != actual_sha or int(pinned_size) != actual_size:
                if not allow_update:
                    raise ChallengeError(f'{child.name}: {image}/{filename} differs from the pinned build '
                                         f'({actual_sha}); a rebuild is a reviewed change, pass --allow-update')
                changed = True
            new_files.append(dict(name=filename, sha256=actual_sha, size=actual_size))
        if not {'vmlinux', 'rootfs.ext4'} <= {entry['name'] for entry in new_files}:
            raise ChallengeError(f'{child.name}: manifest must pin vmlinux and rootfs.ext4')
        content = (MANIFEST_MARKER +
                   f'# Source directory: {child / MANIFEST_PATH}\n'
                   f'# Re-pin a rebuilt image with ./microlab challenges manifest --allow-update.\n' +
                   yaml.safe_dump(dict(image=image, files=new_files), sort_keys=False))
        (child / MANIFEST_PATH).write_text(content)
        written.append(dict(definition=child.name, image=image, changed=changed,
                            files=[dict(name=entry['name'], sha256=entry['sha256']) for entry in new_files]))
    return dict(status='filled' if any(item['changed'] for item in written) else 'unchanged',
                definitions=written)


def download(url, destination):
    if not url.startswith('https://') or '/latest/' in url:
        raise ChallengeError('Downloads require an explicit versioned HTTPS publisher URL')
    try:
        request = urllib.request.Request(url, headers={'User-Agent': 'microlab-challenges/1'})
        with urllib.request.urlopen(request, timeout=60) as response, open(destination, 'wb') as stream:
            if not response.geturl().startswith('https://'):
                raise ChallengeError('Publisher redirected to insecure transport')
            shutil.copyfileobj(response, stream)
    except (urllib.error.URLError, TimeoutError, OSError):
        raise ChallengeError(f'Download failed for {url}; stage the pinned file and use --offline') from None


def publisher_checksum(entry):
    """Optional second source: the publisher's checksums file must agree."""
    try:
        request = urllib.request.Request(entry['publisher_url'], headers={'User-Agent': 'microlab-challenges/1'})
        with urllib.request.urlopen(request, timeout=30) as response:
            text = response.read().decode(errors='replace')
    except (urllib.error.URLError, TimeoutError, OSError):
        return None
    for line in text.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1] == entry['publisher_member'] and \
                re.fullmatch('[0-9a-f]{64}', parts[0]) and parts[0] != entry['sha256']:
            raise ChallengeError('publisher checksum disagrees with the repo pin; refused')
    return True


def elf_machine(data, arch):
    if len(data) < 20 or data[:6] != b'\x7fELF\x02\x01' or struct.unpack('<H', data[18:20])[0] != ELF_MACHINES[arch]:
        raise ChallengeError(f'Expected a Linux 64-bit {arch} ELF binary; wrong architecture or format')


def validate_archive(path, entry, arch):
    if not Path(path).is_file() or digest(path) != entry['sha256']:
        raise ChallengeError(f'traefik: missing archive or SHA256 mismatch at {path}')
    try:
        with tarfile.open(path, 'r:gz') as archive:
            members = {member.name: member for member in archive if member.isfile()}
            member = members.get(entry['member'])
            if member is None:
                raise ChallengeError(f'traefik: archive must contain {entry["member"]}')
            with archive.extractfile(member) as stream:
                data = stream.read()
    except (tarfile.TarError, EOFError, OSError):
        raise ChallengeError(f'traefik: invalid or truncated archive at {path}') from None
    elf_machine(data[:20], arch)
    if hashlib.sha256(data).hexdigest() != entry['member_sha256']:
        raise ChallengeError('traefik: extracted binary SHA256 mismatch against the repo pin')
    return data


def publish(temp, target):
    """Atomic no-clobber rename; same contract as microlab_artifacts."""
    libc = ctypes.CDLL(None, use_errno=True)
    rename = getattr(libc, 'renameat2', None)
    if rename is not None:
        rename.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
        rename.restype = ctypes.c_int
        if rename(-100, os.fsencode(temp), -100, os.fsencode(target), 1) == 0:
            return
        error = ctypes.geterrno()
        if error not in (errno.ENOSYS, errno.EINVAL, errno.ENOTSUP):
            raise OSError(error, os.strerror(error), str(target))
    os.link(temp, target)
    Path(temp).unlink()


def run_artifacts(inventory_path, definitions, directory, offline=False, check=False, lock_path=LOCK):
    inventory = read_yaml(inventory_path)
    _, values = challenge_inventory_values(inventory_path, inventory)
    arch = values.get('micolab_rctf_expected_architecture', 'amd64')
    if arch not in ELF_MACHINES:
        raise ChallengeError('Set micolab_rctf_expected_architecture (amd64 or arm64) '
                             'in the challenge host inventory')
    lock = json.loads(Path(lock_path).read_text())
    entries = lock.get('artifacts', {}).get('traefik', {})
    if arch not in entries:
        raise ChallengeError(f'No pinned Traefik build for {arch}; the lock pins {sorted(entries)}')
    entry = dict(entries[arch])
    if not re.fullmatch(r'\d+\.\d+\.\d+', entry['version']):
        raise ChallengeError('traefik: expected a numeric x.y.z version')
    if not re.fullmatch('[0-9a-fA-F]{64}', entry['sha256']):
        raise ChallengeError('traefik: SHA256 must contain 64 hex characters')
    entry['sha256'] = entry['sha256'].lower()
    directory = Path(directory).resolve()
    if directory.is_symlink():
        raise ChallengeError('Choose an artifact directory without symlink components')
    target = directory / entry['filename']
    if target.exists():
        validate_archive(target, entry, arch)
        action = 'reused'
    elif offline or check:
        raise ChallengeError(f'traefik: missing staged archive {target}; run online or supply the pinned file')
    else:
        directory.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix='.microlab-challenges-', dir=directory)
        os.close(fd)
        try:
            download(entry['url'], tmp)
            validate_archive(tmp, entry, arch)
            # Second source: the published checksums file must agree when it is
            # reachable; silence is tolerated offline, disagreement is fatal.
            publisher_checksum(entry)
            publish(tmp, target)
        finally:
            Path(tmp).unlink(missing_ok=True)
        action = 'downloaded'
    validate_archive(target, entry, arch)
    if check:
        return dict(status='checked', architecture=arch, artifact=dict(
            name='traefik', version=entry['version'], path=str(target),
            sha256=entry['sha256'], binary_sha256=entry['member_sha256'], action=action))
    generated = inventory_path.parent / 'group_vars' / 'microlab_challenge' / GENERATED
    if generated.exists() and not generated.read_text().startswith(MARKER):
        raise ChallengeError(f'{generated}: unrecognized file; refusing to overwrite user content')
    variables = {
        'micolab_rctf_traefik_version': entry['version'],
        'micolab_rctf_traefik_artifact_src': str(target),
        'micolab_rctf_traefik_checksums': {arch: entry['sha256']},
        'micolab_rctf_traefik_binary_sha256': {arch: entry['member_sha256']},
    }
    generated.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix='.microlab-challenges-vars-', dir=generated.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(MARKER + yaml.safe_dump(variables, sort_keys=False))
        os.replace(tmp, generated)
    finally:
        Path(tmp).unlink(missing_ok=True)
    return dict(status='ready', architecture=arch, group_vars=str(generated), artifact=dict(
        name='traefik', version=entry['version'], path=str(target),
        sha256=entry['sha256'], binary_sha256=entry['member_sha256'], action=action))


def emit(result):
    print(json.dumps(dict(schema_version=1, **result)))
    return 0 if result.get('status') in ('ready', 'checked', 'filled', 'unchanged') else 1


def main(argv=None):
    parser = argparse.ArgumentParser(prog='microlab-challenges', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('mode', choices=('check', 'manifest', 'artifacts'))
    parser.add_argument('--inventory', required=True, type=Path)
    parser.add_argument('--definitions', required=True, type=Path)
    parser.add_argument('--images-dir', action='append', default=[], type=Path)
    parser.add_argument('--artifacts-dir', type=Path, default=None)
    parser.add_argument('--allow-update', action='store_true')
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--check', action='store_true', help='Read-only validation; implies offline')
    args = parser.parse_args(argv)
    try:
        args.inventory = args.inventory.expanduser().resolve()
        if not args.inventory.is_file():
            raise ChallengeError('Site inventory missing; run ./microlab setup first')
        if args.mode in ('check', 'manifest'):
            if not args.images_dir:
                raise ChallengeError('Pass at least one --images-dir containing '
                                     '<image>/{vmlinux,rootfs.ext4} from the lab builds')
            directories = [Path(directory).expanduser().resolve() for directory in args.images_dir]
            for directory in directories:
                if not directory.is_dir():
                    raise ChallengeError(f'images directory not found: {directory}')
            if args.mode == 'check':
                return emit(run_check(args.definitions, directories))
            return emit(run_manifest(args.definitions, directories, args.allow_update))
        directory = args.artifacts_dir or Path(__file__).resolve().parents[1] / 'artifacts'
        return emit(run_artifacts(args.inventory, args.definitions, directory,
                                  offline=args.offline, check=args.check))
    except ChallengeError as exc:
        print(json.dumps(dict(schema_version=1, status='error', error=str(exc))))
        return 1
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError):
        print(json.dumps(dict(schema_version=1, status='error',
                              error='Invalid challenge configuration or local I/O failure; '
                                    'check definitions, manifests and permissions')))
        return 1


if __name__ == '__main__':
    sys.exit(main())
